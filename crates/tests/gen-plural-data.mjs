// Writes dialex-cli/src/plural_data.rs: the plural categories CLDR defines per language, as this
// Node's ICU reports them (`Intl.PluralRules(...).resolvedOptions().pluralCategories`), so the
// native `check` does not need Intl. Regional tags that differ from their language are listed too.
import fs from "node:fs";

const ORDER = ["zero", "one", "two", "few", "many"];
const categories = (tag, type) => {
  try {
    return new Intl.PluralRules(tag, { type })
      .resolvedOptions()
      .pluralCategories.filter((c) => c !== "other")
      .sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b));
  } catch {
    return undefined;
  }
};

const letters = "abcdefghijklmnopqrstuvwxyz";
const candidates = new Set();
for (const a of letters) for (const b of letters) candidates.add(a + b);
// three-letter languages with data
for (const tag of [
  "fil",
  "haw",
  "chr",
  "ckb",
  "cmn",
  "ast",
  "bem",
  "ceb",
  "dsb",
  "hsb",
  "kab",
  "ksh",
  "ckb",
  "gsw",
  "jbo",
  "nds",
  "nqo",
  "prg",
  "quc",
  "sah",
  "scn",
  "sdh",
  "seh",
  "shi",
  "smn",
  "sms",
  "syr",
  "tzm",
  "vai",
  "wae",
  "yue",
  "mni",
  "nnh",
  "ssy",
  "ses",
  "osa",
  "mus",
  "lag",
  "kok",
  "jgo",
  "dzo",
  "bez",
  "asa",
  "ebu",
  "teo",
  "tig",
  "trv",
  "und",
]) {
  candidates.add(tag);
}

const languages = {};
for (const tag of candidates) {
  if (Intl.PluralRules.supportedLocalesOf([tag]).length === 0) continue;
  const cardinal = categories(tag, "cardinal");
  const ordinal = categories(tag, "ordinal");
  if (cardinal && ordinal) languages[tag] = [cardinal, ordinal];
}

const regional = {};
for (const tag of [
  "pt-PT",
  "pt-BR",
  "zh-Hant",
  "zh-Hans",
  "zh-TW",
  "zh-CN",
  "zh-HK",
  "sr-Latn",
  "en-GB",
  "en-US",
  "es-419",
  "es-MX",
  "es-ES",
  "fr-CA",
  "fr-FR",
  "de-AT",
  "de-CH",
  "ca-ES",
  "nb-NO",
  "bs-Latn",
  "hr-HR",
  "ro-MD",
  "ru-UA",
  "az-Latn",
  "uz-Latn",
  "pa-Arab",
  "ff-Adlm",
]) {
  const language = tag.split("-")[0];
  const cardinal = categories(tag, "cardinal");
  const ordinal = categories(tag, "ordinal");
  if (!cardinal || !ordinal || !languages[language]) continue;
  if (JSON.stringify([cardinal, ordinal]) !== JSON.stringify(languages[language]))
    regional[tag] = [cardinal, ordinal];
}

const array = (items) => `&[${items.map((c) => JSON.stringify(c)).join(", ")}]`;
const row = ([tag, [cardinal, ordinal]]) =>
  `    (${JSON.stringify(tag)}, ${array(cardinal)}, ${array(ordinal)}),`;

const out = `// Generated by crates/tests/gen-plural-data.mjs (Node ${process.version}, ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Do not edit.

/// (language, cardinal categories, ordinal categories), without \`other\`, in CLDR order.
pub const LANGUAGES: &[(&str, &[&str], &[&str])] = &[
${Object.entries(languages)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(row)
  .join("\n")}
];

/// Regional tags whose categories differ from their language's.
pub const REGIONAL: &[(&str, &[&str], &[&str])] = &[
${Object.entries(regional)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(row)
  .join("\n")}
];
`;
fs.writeFileSync(new URL("../dialex-cli/src/plural_data.rs", import.meta.url), out);
console.log(
  `languages: ${Object.keys(languages).length}, regional: ${Object.keys(regional).length}`,
);
