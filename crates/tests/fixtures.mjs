// Projects the parity scripts run both implementations on.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

import { createProject } from "../../apps/benchmarks/cli/project.mjs";

const root = path.resolve(import.meta.dirname, "../..");
const node = path.join(root, "packages/cli/dist/index.mjs");

export function buildFixtures(tmp) {
  const fixtures = [];
  const synthetic = path.join(tmp, "synthetic-100");
  createProject(synthetic, 100);
  fixtures.push(["synthetic-100", synthetic]);
  for (const name of fs.readdirSync(path.join(root, "examples"))) {
    const dir = path.join(root, "examples", name);
    if (fs.statSync(dir).isDirectory() && fs.existsSync(path.join(dir, "package.json"))) {
      fixtures.push([`examples/${name}`, dir]);
    }
  }

  // Projects that are full of problems, to compare the diagnostics and not just the happy path
  function issuesProject(dir, { formatted = false, lint = false } = {}) {
    fs.rmSync(dir, { recursive: true, force: true });
    const write = (file, text) => {
      fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
      fs.writeFileSync(path.join(dir, file), text);
    };
    write("package.json", JSON.stringify({ name: "issues", dependencies: { hono: "^4" } }));
    // the config imports dialexjs; resolve it to this repository's build
    fs.mkdirSync(path.join(dir, "node_modules"), { recursive: true });
    fs.symlinkSync(path.join(root, "packages/core"), path.join(dir, "node_modules/dialexjs"));
    write("tsconfig.json", JSON.stringify({ compilerOptions: { moduleResolution: "bundler" } }));
    write(
      "dialex.config.ts",
      lint
        ? `import { defineConfig } from "dialexjs";
export default defineConfig({
  defaultLocale: "en",
  locales: ["en", "tr", "de"],
  lint: { rules: { "missing-key": "warn", "unused-key": "off", "unknown-dictionary": ["warn", {}] } },
});
`
        : `import { defineConfig } from "dialexjs";\nexport default defineConfig({ defaultLocale: "en", locales: ["en", "tr", "de"] });\n`,
    );
    if (lint) {
      // comments, `dialex-ignore` directives and a dictionary registered in code
      write(
        "src/comments.ts",
        `import { getDictionary } from "./i18n";
// getDictionary("commented-out")
/* t("a.commented") */
// dialex-ignore-next-line
getDictionary("ignored-next");
getDictionary("ignored-same"); // dialex-ignore
const url = "http://example.com"; getDictionary("after-url");
createDialexServer({ dictionaries: { inline_dict: {}, "kebab-dict": {} } });
getDictionary("inline_dict");
getDictionary("kebab-dict");
`,
      );
    }
    write(
      "src/features/a/a.content.ts",
      `import { defineDictionary } from "dialexjs";

export default defineDictionary("a", {
  en: {
    title: "Title",
    only_en: "x",
    nav: { home: "Home", about: "About" },
    greeting: "Hello {name}",
    items: "{count, plural, one {# item} other {# items}}",
    broken: "{ oops",
    soft: "a { b",
    mismatch: "{a} and {b}",
    todo: "[TODO] write me",
    ordinal: "{n, selectordinal, one {#st} two {#nd} few {#rd} other {#th}}",
    role: "{role, select, admin {A} other {O}}",
    fn: (n: number) => \`n=\${n}\`,
  },
  tr: {
    title: "Başlık",
    nav: { home: "Ana sayfa" },
    greeting: "Merhaba {ad}",
    items: "{count, plural, one {# öğe}}",
    extra_tr: "y",
    broken: "ok {x",
    mismatch: "{a}",
    todo: "[TODO] yaz",
    ordinal: "{n, selectordinal, other {#.}}",
    role: "{role, select, admin {Y} other {D}}",
    fn: (n: number) => \`n=\${n}\`,
  },
});
`,
    );
    write(
      "src/features/b/b.content.ts",
      `import { defineDictionary } from "dialexjs";

export default defineDictionary({
  name: "b",
  dictionary: {
    en: { hello: "Hello" },
    tr: { hello: "Merhaba" },
  },
});
`,
    );
    write(
      "src/features/c/c.content.ts",
      `import { defineDictionary } from "dialexjs";
export default defineDictionary("c", { en: { never: "x" }, tr: { never: "y" }, de: { never: "z" } });
`,
    );
    write(
      "src/page.ts",
      `import { t, getDictionary } from "./i18n";
export const x = [
  t("a.title"),
  t("a.nav.home"),
  t("a.nope"),
  t("b.hello"),
  getDictionary("zzz"),
  getDictionary('a'),
  t("other.lib.key"),
];
`,
    );
    write(
      "src/i18n.ts",
      "export const t = (k: string) => k; export const getDictionary = (n: string) => n;\n",
    );
    write(
      "dialex.lock.json",
      JSON.stringify({
        version: 1,
        sourceLocale: "en",
        locales: { tr: { "a.title": "deadbeef", "a.nav.home": "00000000" } },
      }),
    );
    write(
      "src/dialex.generated.ts",
      formatted
        ? "// formatted\n"
        : "// Auto-generated by dialex CLI. Do not edit directly.\nexport const dictionaries = [];\n",
    );
    write("src/dialex-env.d.ts", "declare module 'dialexjs' {}\n");
    if (formatted) {
      // Let the Node CLI write the real files, then reformat them the way Prettier would
      const generated = spawnSync(process.execPath, [node, "generate"], {
        cwd: dir,
        encoding: "utf-8",
        env: { ...process.env, NO_COLOR: "1" },
      });
      if (generated.status !== 0) throw new Error(generated.stderr);
      for (const file of ["src/dialex.generated.ts", "src/dialex-env.d.ts"]) {
        const text = fs.readFileSync(path.join(dir, file), "utf-8");
        fs.writeFileSync(
          path.join(dir, file),
          text
            .replace(/;\n/g, ";\n\n")
            .replace(/"([A-Za-z]+)"/g, "'$1'")
            .replace(/\n  /g, "\n    "),
        );
      }
    }
  }
  const issues = path.join(tmp, "issues");
  issuesProject(issues);
  fixtures.push(["issues", issues]);
  const formatted = path.join(tmp, "issues-formatted");
  issuesProject(formatted, { formatted: true });
  fixtures.push(["issues-formatted", formatted]);
  const linted = path.join(tmp, "issues-lint");
  issuesProject(linted, { lint: true });
  fixtures.push(["issues-lint", linted]);

  return fixtures;
}
