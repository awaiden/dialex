/**
 * The adapter entry points to augment for a project, read from its `package.json`. Falls back to
 * all of them when nothing is recognised, so types never silently go missing.
 */
export function detectAdapters(root: string): string[] {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf-8"));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies, ...pkg.peerDependencies };
    const found = new Set<string>();
    for (const name of Object.keys(deps)) {
      for (const adapter of ADAPTER_DEPENDENCIES[name] ?? []) found.add(adapter);
    }
    if (found.size > 0) return REGISTRY_ADAPTERS.filter((adapter) => found.has(adapter));
  } catch {
    // no readable package.json
  }
  return [...REGISTRY_ADAPTERS];
}

/**
 * The `dialex-env.d.ts` a project should have: its path and contents, or `undefined` when there
 * are no dictionary files. Nothing is written.
 */
export function renderDts(
  root: string,
  files: string[],
  locales?: string[],
  messageArguments: Record<string, string> = {},
): { path: string; content: string } | undefined {
  if (files.length === 0) return undefined;

  const dtsDir = fs.existsSync(path.join(root, "src")) ? path.join(root, "src") : root;
  const imports: string[] = [];
  const records: string[] = [];

  files.forEach((file, index) => {
    let relPath = path.relative(dtsDir, file).replace(/\\/g, "/");
    relPath = relPath.replace(/\.ts$/, "");
    if (!relPath.startsWith(".")) {
      relPath = "./" + relPath;
    }

    imports.push(`import dict${index} from '${relPath}';`);
    records.push(
      `Record<typeof dict${index}['name'], typeof dict${index}['dictionary'][keyof typeof dict${index}['dictionary']]>`,
    );
  });

  const localesType =
    locales && locales.length > 0 ? locales.map((l) => `"${l}"`).join(" | ") : "string";

  const registry = records.join(",\n    ");
  const messageEntries = Object.entries(messageArguments)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, type]) => `    ${JSON.stringify(key)}: ${type};`)
    .join("\n");
  const adapterBlocks = detectAdapters(root)
    .map(
      (adapter) => `
declare module 'dialexjs/${adapter}' {
  export interface DictionaryRegistry extends ${registry} {}
}
`,
    )
    .join("");

  const dtsContent = `/* eslint-disable */
// @ts-nocheck
// Generated by dialex
${imports.join("\n")}

declare module 'dialexjs' {
  export interface Register {
    locales: ${localesType};
  }
  export interface DictionaryRegistry extends ${records.join(",\n    ")} {}
  export interface MessageArguments {${messageEntries ? `\n${messageEntries}\n  ` : ""}}
}
${adapterBlocks}
`;

  return { path: path.join(dtsDir, "dialex-env.d.ts"), content: dtsContent };
}

export function generateDts(root: string, files: string[], locales?: string[]) {
  const dts = renderDts(root, files, locales);
  if (!dts) return;
  const existing = fs.existsSync(dts.path) ? fs.readFileSync(dts.path, "utf-8") : "";
  if (existing !== dts.content) {
    fs.mkdirSync(path.dirname(dts.path), { recursive: true });
    fs.writeFileSync(dts.path, dts.content, "utf-8");
  }
}

let scanned = false;

/**
 * Auto-scans all dictionary files (**\/*.content.ts) in the project,
 * imports them into memory, registers them, and ensures TypeScript declaration types are generated.
 */
export async function autoScanAndLoadDictionaries(
  root: string = process.cwd(),
  inlineConfig: DialexConfig = {},
): Promise<Record<string, Record<string, any>>> {
  const config = resolveDialexConfig(root, inlineConfig);
  const include = config.include || "**/*.content.ts";
  const files = fg.sync(include, { cwd: root, absolute: true, ignore: ["**/node_modules/**"] });

  // Dynamically load each dictionary into memory if not already done
  if (!scanned) {
    for (const file of files) {
      try {
        const fileUrl = pathToFileURL(file).href;
        await import(fileUrl);
      } catch {
        // Continue if dynamic import is handled elsewhere
      }
    }
    scanned = true;
  }

  return globalDictionaries;
}
