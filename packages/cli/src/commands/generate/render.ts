import fs from "node:fs";
import path from "node:path";

import { DEFAULT_CONFIG } from "dialexjs";

import { listLocales, parseDictionaryText } from "../../utils/dictionary/index.js";
import { scanFiles } from "../../utils/files.js";
import { messageArguments } from "../../utils/message-arguments.js";
import { renderDts, resolveDialexConfig } from "../../utils/scanner.js";
import { splitLocales } from "../../utils/split-locales.js";
import { readStaticConfig } from "../../utils/static-config.js";
import { relativeImportExtension } from "../../utils/tsconfig.js";
import type { GenerateOptions, RenderedGenerate } from "./types.js";

/** The folder, next to `dialex.generated.ts`, that holds the per-locale modules. */
export const LOCALES_DIR = "dialex.locales";
const safeName = (text: string) => text.replace(/[^A-Za-z0-9._-]/g, "_");

/**
 * Works out `dialex.generated.ts` and `dialex-env.d.ts` for a project without writing anything,
 * so `check` can tell whether they are up to date.
 *
 * Settings come from `dialex.config.*` and fall back to {@link DEFAULT_CONFIG}; `locales` falls
 * back to the locales the dictionaries define.
 */
export function renderGenerated(root: string, options: GenerateOptions = {}): RenderedGenerate {
  const inlineConfig = options.config ? { configFile: options.config } : {};
  const staticRead = readStaticConfig(root, options.config);
  const config = options.static ? staticRead.config : resolveDialexConfig(root, inlineConfig);
  const include = config.include || DEFAULT_CONFIG.include;

  const found = scanFiles(root, include, { exclude: config.exclude }).sort();

  const srcDir = fs.existsSync(path.join(root, "src")) ? path.join(root, "src") : root;
  const outputOption = options.output ?? config.output;
  const outputPath = outputOption
    ? path.resolve(root, outputOption)
    : path.join(srcDir, "dialex.generated.ts");
  const outputDir = path.dirname(outputPath);
  // A broad `include` (like `src/**/*.ts`) would otherwise match the files generated here
  const files = found.filter(
    (file) =>
      file !== outputPath &&
      !file.endsWith(".d.ts") &&
      path.basename(file) !== "dialex.generated.ts",
  );

  // Read each dictionary's name and locales from its syntax tree; project code is never run.
  const parsed = files.map((file) => parseDictionaryText(file, fs.readFileSync(file, "utf-8")));
  const inferred: string[] = [];
  for (const df of parsed) {
    if (df)
      for (const locale of listLocales(df)) if (!inferred.includes(locale)) inferred.push(locale);
  }
  const locales = config.locales?.length ? config.locales : inferred;

  const clientConfig = {
    defaultLocale: config.defaultLocale || DEFAULT_CONFIG.defaultLocale,
    locales,
    fallbacks: config.fallbacks ?? DEFAULT_CONFIG.fallbacks,
    prefixDefault: config.prefixDefault ?? DEFAULT_CONFIG.prefixDefault,
    lazy: config.lazy ?? DEFAULT_CONFIG.lazy,
  };

  const extension = relativeImportExtension(root);
  const importPath = (file: string) => {
    let rel = path.relative(outputDir, file).replace(/\\/g, "/").replace(/\.ts$/, extension);
    if (!rel.startsWith(".")) rel = "./" + rel;
    return rel;
  };

  const header = `// Auto-generated by dialex CLI. Do not edit directly.
/* eslint-disable */
// @ts-nocheck`;
  // "locale" must stay a literal type, or `<DialexProvider {...dialex}>` would not type-check
  const configJson = JSON.stringify(clientConfig, null, 2).replace(
    '"lazy": "locale"',
    '"lazy": "locale" as const',
  );
  const configExport = `export const config = ${configJson};

${
  locales.length > 0
    ? `export const locales = ${JSON.stringify(locales)} as const;\nexport type Locale = (typeof locales)[number];`
    : "export const locales: readonly string[] = [];\nexport type Locale = string;"
}`;

  const extraFiles: { path: string; content: string }[] = [];
  const notes: string[] = [];
  const takenNames = new Set<string>();

  let content: string;
  if (clientConfig.lazy) {
    // Only dynamic imports, so bundlers can split each dictionary (or, with "locale", each
    // locale of it) into its own chunk.
    const loaders = files.map((file, i) => {
      const df = parsed[i];
      const name = df?.name;
      if (!name || !df) {
        throw new Error(
          `Cannot determine the dictionary name of ${path.relative(root, file)} for lazy loading. ` +
            'Use defineDictionary("name", ...) or a literal `name` property.',
        );
      }
      const whole = `  ${JSON.stringify(name)}: () => import("${importPath(file)}"),`;
      if (clientConfig.lazy !== "locale") return whole;

      const split = splitLocales(df);
      if (!split.ok) {
        notes.push(
          `${path.relative(root, file)} is loaded whole, not per locale: ${split.reason}.`,
        );
        return whole;
      }
      let base = safeName(name);
      for (let n = 2; takenNames.has(base); n++) base = `${safeName(name)}-${n}`;
      takenNames.add(base);

      const entries = split.slices.map((slice) => {
        const target = path.join(outputDir, LOCALES_DIR, `${base}.${safeName(slice.locale)}.ts`);
        extraFiles.push({
          path: target,
          content: `${header}\nexport default ${slice.code};\n`,
        });
        return `    ${JSON.stringify(slice.locale)}: () => import("${importPath(target)}"),`;
      });
      return `  ${JSON.stringify(name)}: {\n${entries.join("\n")}\n  },`;
    });
    content = `${header}

export const dictionaries = [];

export const dictionaryMap = {};

export const loaders = {
${loaders.join("\n")}
};

${configExport}

export const dialex = { dictionaries, config, loaders };

export default dictionaries;
`;
  } else {
    const ids = files.map((_, i) => `dict_${i}`);
    const dictList = ids.length <= 1 ? `[${ids.join(", ")}]` : `[\n  ${ids.join(",\n  ")}\n]`;
    content = `${header}
${files.map((file, i) => `import ${ids[i]} from "${importPath(file)}";`).join("\n")}

export const dictionaries = ${dictList};

export const dictionaryMap = {
${ids.map((id) => `  [${id}.name]: ${id}.dictionary,`).join("\n")}
};

${configExport}

export const dialex = { dictionaries, config };

export default dictionaries;
`;
  }

  const dts = renderDts(
    root,
    files,
    locales,
    messageArguments(parsed, clientConfig.defaultLocale),
    outputOption ? outputDir : undefined,
  );
  return {
    files,
    outputPath,
    content,
    dtsPath: dts?.path ?? path.join(outputOption ? outputDir : srcDir, "dialex-env.d.ts"),
    dtsContent: dts?.content,
    configFile: staticRead.file,
    extraFiles,
    notes,
  };
}
